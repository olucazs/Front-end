// OPERADORES

let a = 15;
let b = 5;

// Este código soma os números e imprime o resultado no console
let sum = a + b;
console.log(`The sum of ${a} and ${b} is ${sum}.`);

// Este código multiplica os números e imprime o resultado no console
let multiplication = a * b;
console.log(`The multiplication of ${a} and ${b} is ${multiplication}.`);

// Este código divide os números e imprime o resultado no console
let division = a / b;
console.log(`The division of ${a} by ${b} is ${division}.`);

// Este código subtrai os números e imprime o resultado no console
let subtraction = a - b;
console.log(`The subtraction of ${b} from ${a} is ${subtraction}.`);

// Este código exponencia os números e imprime o resultado no console
let exponentiation = a ** b;
console.log(`The exponentiation of ${a} to the power of ${b} is ${exponentiation}.`);

// Este código incrementa os números e imprime o resultado no console
let increment = a++;
console.log(`The increment of ${a} is ${increment}.`);

// Este código decrementa os números e imprime o resultado no console
let decrement = b--;
console.log(`The decrement of ${b} is ${decrement}.`);

// Este código calcula o resto da divisão dos números e imprime o resultado no console
let remainder = a % b;
console.log(`The remainder of the division of ${a} by ${b} is ${remainder}.`);